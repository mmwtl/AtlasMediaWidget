#!/usr/bin/env python3
"""Generates the one-tone player logos for the source tiles.

Two sources, both 24x24 SVGs filled with one colour:
- Simple Icons (https://simpleicons.org, CC0) for the slugs in SIMPLE_ICONS;
- docs/assets/player-icons/<name>.svg for players Simple Icons lacks (see the README there).

Each icon becomes app/src/main/res/drawable/ic_player_<name>.xml, filled white and tinted to the
card's text colour at runtime. Rerun this script instead of editing the drawables; --from reads
already downloaded Simple Icons <slug>.svg files instead of the network. The package names that
use each logo live in PlayerIconStyle.CURATED.
"""
import argparse
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ElementTree

SIMPLE_ICONS_URL = "https://raw.githubusercontent.com/simple-icons/simple-icons/develop/icons/{}.svg"
SIMPLE_ICONS = [
    "applemusic", "audible", "castbox", "deezer", "kodi", "plex", "pocketcasts",
    "podcastaddict", "soundcloud", "spotify", "tidal", "vk", "youtubemusic",
]
# docs/assets/player-icons file -> drawable name. A local file wins over Simple Icons.
LOCAL_ICONS = {
    "aimp.svg": "aimp",
    "foobar2000.svg": "foobar2000",
    "kion-music.svg": "kionmusic",
    "murglar.svg": "murglar",
    "musicolet.svg": "musicolet",
    "poweramp.svg": "poweramp",
    "stellio.svg": "stellio",
    "vk-music.svg": "vkmusic",
    "vlc.svg": "vlc",
    "waves-of-sound.svg": "wavesofsound",
    "yandex-music.svg": "yandexmusic",
    "yandex-radio.svg": "yandexradio",
    "zvuk.svg": "zvuk",
}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCAL_DIR = os.path.join(ROOT, "docs", "assets", "player-icons")
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
SVG = "{http://www.w3.org/2000/svg}"
TRANSFORM = re.compile(
    r"^\s*translate\(\s*([-\d.]+)[ ,]+([-\d.]+)\s*\)\s*scale\(\s*([-\d.]+)\s*\)\s*$")


def vector_path(element, indent):
    attributes = ['android:fillColor="#FFFFFFFF"']
    if element.get("fill-rule") == "evenodd":
        attributes.append('android:fillType="evenOdd"')
    attributes.append('android:pathData="' + element.get("d") + '"')
    pad = " " * indent
    path = pad + "<path\n" + "".join(pad + "    " + a + "\n" for a in attributes[:-1])
    path += pad + "    " + attributes[-1] + " />\n"
    transform = element.get("transform")
    if not transform:
        return path
    match = TRANSFORM.match(transform)
    if not match:
        raise ValueError("unsupported transform: " + transform)
    x, y, scale = match.groups()
    return (
        pad + "<group\n"
        + pad + '    android:translateX="' + x + '"\n'
        + pad + '    android:translateY="' + y + '"\n'
        + pad + '    android:scaleX="' + scale + '"\n'
        + pad + '    android:scaleY="' + scale + '">\n'
        + vector_path_without_transform(element, indent + 4)
        + pad + "</group>\n"
    )


def vector_path_without_transform(element, indent):
    copy = ElementTree.Element(element.tag, {k: v for k, v in element.attrib.items()
                                             if k != "transform"})
    return vector_path(copy, indent)


def convert(name, svg, credit):
    root = ElementTree.fromstring(svg)
    if root.get("viewBox") != "0 0 24 24":
        raise ValueError(name + ": expected a 24x24 view box")
    paths = root.findall(SVG + "path")
    if not paths or len(paths) != len(list(root.iter())) - 1 - len(root.findall(SVG + "title")):
        raise ValueError(name + ": only <path> and <title> elements are supported")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- " + credit + "; generated by tools/make_player_icons.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        '    android:viewportWidth="24"\n'
        '    android:viewportHeight="24">\n'
        + "".join(vector_path(path, 4) for path in paths)
        + "</vector>\n"
    )


def write(name, content):
    target = os.path.join(OUT, "ic_player_" + name + ".xml")
    with open(target, "w", encoding="utf-8") as file:
        file.write(content)
    print("wrote", os.path.relpath(target, ROOT))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from", dest="local", help="directory with downloaded <slug>.svg files")
    args = parser.parse_args()
    for slug in SIMPLE_ICONS:
        if args.local:
            with open(os.path.join(args.local, slug + ".svg"), encoding="utf-8") as file:
                svg = file.read()
        else:
            with urllib.request.urlopen(SIMPLE_ICONS_URL.format(slug), timeout=30) as response:
                svg = response.read().decode("utf-8")
        title = ElementTree.fromstring(svg).find(SVG + "title").text
        write(slug, convert(slug, svg, title + " logo from Simple Icons (CC0)"))
    for file_name, name in LOCAL_ICONS.items():
        with open(os.path.join(LOCAL_DIR, file_name), encoding="utf-8") as file:
            svg = file.read()
        write(name, convert(name, svg, "docs/assets/player-icons/" + file_name))
    return 0


if __name__ == "__main__":
    sys.exit(main())
